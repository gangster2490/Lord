package de.spardirekt.recipeveo.domain

/**
 * On-device culinary agent: one dish name in, a full Russian package out.
 * No photos, no settings, no API key.
 */
object CulinaryAgent {
    fun create(rawName: String, now: Long = System.currentTimeMillis()): CulinaryPackage {
        val dish = rawName.trim().replace(Regex("\\s+"), " ")
        require(StudioRules.canCreate(dish)) { "Введите название блюда." }
        val title = dish.replaceFirstChar { it.uppercase() }
        val kind = Kind.classify(dish)
        val recipe = recipeFor(title, kind)
        val voiceover = voiceoverFor(title, kind)
        return CulinaryPackage(
            dish = title,
            recipe = recipe,
            veoPrompt = veoPrompt(title, kind, recipe, voiceover),
            negativePrompt = negativePrompt(title),
            voiceover = voiceover,
            tiktokTitle = tiktokTitle(title, kind),
            hashtags = hashtags(title),
            createdAt = now,
        )
    }

    private enum class Kind {
        SOUP, RICE, SALAD, DUMPLING, PANCAKE, PASTA, MEAT, FISH, DESSERT, PASTRY, DRINK, PLATE;

        companion object {
            fun classify(name: String): Kind {
                val n = name.lowercase()
                fun has(vararg keys: String) = keys.any { n.contains(it) }
                return when {
                    has("борщ", "щи", "солянка", "уха", "харчо", "суп", "похлёб", "окрошка", "рассольник", "гаспачо", "том ям", "мисо") -> SOUP
                    has("плов", "ризотто", "паэлья", "каша", "пшён", "гречк", "булгур", "кус-кус", "рис") -> RICE
                    has("салат", "оливье", "винегрет", "цезарь", "греческ", "капрезе", "кимчи") -> SALAD
                    has("пельмен", "вареник", "хинкал", "мант", "гедза", "dumpling", "равиол") -> DUMPLING
                    has("блин", "олад", "сырник", "панкейк", "драник") -> PANCAKE
                    has("паста", "спагетти", "карбонар", "лазанья", "пенне", "фетучин", "болоньез") -> PASTA
                    has("шашлык", "стейк", "котлет", "курица", "куриц", "говядин", "свинин", "мясо", "люля", "ребра", "бургер", "каре") -> MEAT
                    has("рыб", "лосос", "сёмг", "селёд", "треск", "форел", "судак", "тунец") -> FISH
                    has("торт", "чизкейк", "пирожн", "тирамису", "медовик", "наполеон", "эклер", "морожен", "мусс", "паннакота", "брауни") -> DESSERT
                    has("пирог", "кулебяк", "курник", "киш", "пицца", "хачапур", "focaccia", "булка") -> PASTRY
                    has("компот", "морс", "смузи", "коктейл", "лимонад", "какао", "горячий шоколад", "чай", "кофе") -> DRINK
                    else -> PLATE
                }
            }
        }
    }

    private fun recipeFor(dish: String, kind: Kind): Recipe {
        val known = knownRecipes[dish.lowercase()]
        if (known != null) return known.copy(dish = dish)
        return fallbackRecipe(dish, kind)
    }

